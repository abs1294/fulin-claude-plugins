// 把指定 entry 在中央目錄與本地標頭的壓縮方式改成不存在的 99：解壓必定失敗
function breakEntry(file, entry) {
  const b = fs.readFileSync(file);
  const name = Buffer.from(entry);
  for (let i = 0; i + 46 < b.length; i++) {
    if (b.readUInt32LE(i) === 0x02014b50 && b.subarray(i + 46, i + 46 + name.length).equals(name)) { b.writeUInt16LE(99, i + 10); b.writeUInt16LE(99, b.readUInt32LE(i + 42) + 8); }
  }
  fs.writeFileSync(file, b);
  return file;
}
