let pass = 0, fail = 0;
function t(label, ok, detail) {
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${label}${ok ? '' : '  → ' + detail}`);
  ok ? pass++ : fail++;
}
function py(code, ...args) {
  for (const exe of ['python', 'python3', 'py']) {
    const r = spawnSync(exe, ['-c', code, ...args], { encoding: 'utf8' });
    if (r.error && r.error.code === 'ENOENT') continue;
    if (r.status !== 0) throw new Error(r.stderr);
    return r.stdout;
  }
  throw new Error('找不到 python');
}
// files：{ entry: 內容 }，寫成 zip
function zip(file, files) {
  py(`
import sys, json, zipfile
with zipfile.ZipFile(sys.argv[2], 'w', zipfile.ZIP_DEFLATED) as z:
    for k, v in json.loads(sys.argv[1]).items(): z.writestr(k, v.encode('utf-8'))
`, JSON.stringify(files), file);
  return file;
}
function check(args) {
  const r = spawnSync(process.execPath, [CHECK, ...args], { encoding: 'utf8' });
  return { code: r.status, out: r.stdout + r.stderr };
}

